#!/usr/bin/env node
/**
 * Generate the MySQL migration covering models the checked-in migrations miss
 * (finding #9).
 *
 * `prisma/migrations/` held five MySQL DDL files describing 40 of the 52
 * canonical models. The twelve Jara models added later existed only in
 * `prisma/schema.prisma`, so a MySQL deployment built from the migrations lacked
 * those tables while the SQLite runtime had them.
 *
 * `prisma migrate diff` cannot run here (the schema engine binary is not
 * downloadable in this environment), and hand-writing twelve tables is how the
 * drift appeared in the first place. The migration is therefore generated from
 * the canonical schema with the same parser the SQLite DDL uses.
 *
 *   node scripts/generate-mysql-migration.mjs           # write
 *   node scripts/generate-mysql-migration.mjs --check   # verify only
 *
 * The output is additive: CREATE TABLE IF NOT EXISTS plus supporting indexes.
 */

import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseSchema, sqlDefault, SCALARS } from './lib/prisma-parse.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const CANONICAL = join(ROOT, 'prisma/schema.prisma')
const MIGRATIONS = join(ROOT, 'prisma/migrations')
const NAME = '20261124000000_complete_jara_tables'

/** Columns whose text content needs MySQL's TEXT type rather than VARCHAR. */
const WIDE = /(bio|content|caption|description|body|detail|value|notes?|summary|prompt|response|transcript|metadata|data|payload|options|tags|settings|config|preview|excerpt|message|reason|address|url|key|token)$/i

const SQL_TYPE = {
  String: 'VARCHAR(191)',
  Int: 'INTEGER',
  BigInt: 'BIGINT',
  Float: 'DOUBLE',
  Decimal: 'DECIMAL(65,30)',
  Boolean: 'TINYINT(1)',
  DateTime: 'DATETIME(3)',
  Json: 'JSON',
  Bytes: 'LONGBLOB',
}

const ACTIONS = {
  Cascade: 'CASCADE',
  SetNull: 'SET NULL',
  Restrict: 'RESTRICT',
  NoAction: 'NO ACTION',
  Default: 'RESTRICT',
}

function tablesCoveredByExistingMigrations() {
  const covered = new Set()
  if (!existsSync(MIGRATIONS)) return covered
  for (const entry of readdirSync(MIGRATIONS, { withFileTypes: true })) {
    if (!entry.isDirectory() || entry.name === NAME) continue
    const file = join(MIGRATIONS, entry.name, 'migration.sql')
    if (!existsSync(file)) continue
    const sql = readFileSync(file, 'utf8')
    for (const match of sql.matchAll(/CREATE TABLE (?:IF NOT EXISTS )?`(\w+)`/g)) covered.add(match[1])
    for (const match of sql.matchAll(/ALTER TABLE `(\w+)`/g)) covered.add(match[1])
  }
  return covered
}

/**
 * Indexed and constrained columns must stay VARCHAR: MySQL cannot create an
 * index (including a UNIQUE index or a foreign key) on a TEXT column without a
 * prefix length, and a prefix length would make the uniqueness guarantee wrong.
 */
function mustStayShort(model, fieldName) {
  if (/@id\b|@unique\b/.test(model.fields[fieldName].attrs)) return true
  for (const unique of model.uniques) {
    if (unique.includes(fieldName)) return true
  }
  for (const line of (model.indexedColumns ?? [])) {
    if (line.includes(fieldName)) return true
  }
  // Foreign-key columns are compared against a VARCHAR(191) primary key.
  for (const [name, field] of Object.entries(model.fields)) {
    if (SCALARS.has(field.type)) continue
    const join = field.attrs.match(/fields:\s*\[([^\]]+)\]/)
    if (join && join[1].split(',').map((c) => c.trim()).includes(name === fieldName ? fieldName : fieldName)) {
      // handled below
    }
    if (join && join[1].split(',').map((c) => c.trim()).includes(fieldName)) return true
  }
  return false
}

function mysqlType(model, field) {
  const base = SQL_TYPE[field.type] ?? 'VARCHAR(191)'
  if (field.type === 'String' && WIDE.test(field.name) && !mustStayShort(model, field.name)) return 'TEXT'
  return base
}

function columnDefinition(model, field) {
  const isId = /@id\b/.test(field.attrs)
  const isUnique = /@unique\b/.test(field.attrs) && !isId
  let sql = `  \`${field.name}\` ${mysqlType(model, field)}`

  if (!field.optional && !field.isList) sql += ' NOT NULL'

  const isNowDefault = /@default\(now\(\)\)/.test(field.attrs) || /@updatedAt\b/.test(field.attrs)

  if (isId) {
    // cuid()/uuid() identifiers are generated by the application, not MySQL.
    const appGenerated = /cuid\(\)|uuid\(\)|ulid\(\)|nanoid\(\)/.test(field.attrs)
    if (!appGenerated) {
      if (isNowDefault && field.type === 'DateTime') {
        sql += ' DEFAULT CURRENT_TIMESTAMP(3)'
      } else {
        const def = sqlDefault(field)
        if (def !== null) sql += ` DEFAULT ${def}`
      }
    }
    sql += ' PRIMARY KEY'
  } else if (isNowDefault && field.type === 'DateTime') {
    sql += ' DEFAULT CURRENT_TIMESTAMP(3)'
  } else {
    const def = sqlDefault(field)
    if (def !== null) sql += ` DEFAULT ${def}`
  }
  return { sql, isUnique }
}

function createTable(model) {
  const columns = []
  const keys = []

  for (const field of Object.values(model.fields)) {
    if (!SCALARS.has(field.type)) continue
    const { sql, isUnique } = columnDefinition(model, field)
    columns.push(sql)
    if (isUnique) keys.push(`  UNIQUE INDEX \`${model.table}_${field.name}_key\`(\`${field.name}\`)`)
  }

  for (const unique of model.uniques) {
    keys.push(`  UNIQUE INDEX \`${model.table}_${unique.join('_')}_key\`(${unique.map((c) => `\`${c}\``).join(', ')})`)
  }

  for (const field of Object.values(model.fields)) {
    if (SCALARS.has(field.type)) continue
    const join_ = field.attrs.match(
      /@relation\(\s*(?:"[^"]*"\s*,\s*)?(?:fields:\s*\[([^\]]+)\]\s*,\s*references:\s*\[([^\]]+)\][^)]*)?(?:onDelete:\s*(\w+))?/,
    )
    if (!join_ || !join_[1]) continue
    const localColumn = join_[1].split(',')[0].trim()
    const referenced = join_[2].split(',')[0].trim()
    const target = model.fields[field.name]
    const targetTable = referencedModelTable(field.type)
    if (!targetTable) continue
    const onDelete = ACTIONS[join_[3] ?? 'Cascade']
    keys.push(
      `  CONSTRAINT \`${model.table}_${localColumn}_fkey\` FOREIGN KEY (\`${localColumn}\`) REFERENCES \`${targetTable}\`(\`${referenced}\`) ON DELETE ${onDelete} ON UPDATE CASCADE`,
    )
  }

  // MySQL does not allow an index on a TEXT column without a prefix length, and
  // the model-level indexes only ever cover short columns, so they are safe.
  for (const match of JSON.stringify(model).match(/"@(@index[^"]*)"/g) ?? []) void match

  return `CREATE TABLE IF NOT EXISTS \`${model.table}\` (\n${[...columns, ...keys].join(',\n')}\n) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;`
}

let MODEL_INDEX = new Map()
function referencedModelTable(modelName) {
  return MODEL_INDEX.get(modelName)?.table ?? null
}

function indexStatements(model) {
  const statements = []
  for (const [fieldName, field] of Object.entries(model.fields)) {
    const match = field.attrs.match(/^@@index\(\[([^\]]+)\](?:,\s*map:\s*"([^"]+)")?\)/)
    void fieldName
    void match
  }
  return statements
}

const source = readFileSync(CANONICAL, 'utf8')
const { models, order } = parseSchema(source)
MODEL_INDEX = new Map(Object.entries(models))

const covered = tablesCoveredByExistingMigrations()
// A table counts as covered when an existing migration creates it OR another
// statement in this batch will.
const missing = order.map((name) => models[name]).filter((model) => !covered.has(model.table))

if (!missing.length) {
  console.log('PASS: every canonical model is covered by a checked-in migration.')
  process.exit(0)
}

// Indexes declared at model level. Parsed here because `parseIndexes` emits
// SQLite syntax; the column list is provider-neutral.
function modelIndexes(model, body) {
  const out = []
  for (const line of body.split('\n')) {
    const trimmed = line.replace(/\/\/.*$/, '').trim()
    const match = trimmed.match(/^@@index\(\[([^\]]+)\](?:,\s*(?:map|name):\s*"([^"]+)")?\)/)
    if (!match) continue
    const cols = match[1].split(',').map((c) => c.trim().split('(')[0].trim())
    const name = match[2] ?? `${model.table}_${cols.join('_')}_idx`
    out.push(`CREATE INDEX \`${name}\` ON \`${model.table}\`(${cols.map((c) => `\`${c}\``).join(', ')});`)
  }
  return out
}

// Recover each model's raw body so model-level @@index lines can be emitted.
const bodies = new Map()
for (const match of source.matchAll(/^model\s+(\w+)\s*\{([\s\S]*?)^\}/gm)) bodies.set(match[1], match[2])

const sections = []
for (const model of missing) {
  // Record model-level indexed columns so `mysqlType` keeps them VARCHAR.
  model.indexedColumns = []
  for (const line of (bodies.get(model.name) ?? '').split('\n')) {
    const match = line.replace(/\/\/.*$/, '').trim().match(/^@@(?:index|unique)\(\[([^\]]+)\]/)
    if (match) model.indexedColumns.push(match[1].split(',').map((c) => c.trim().split('(')[0].trim()).join(','))
  }

  const indexes = modelIndexes(model, bodies.get(model.name) ?? '')
  sections.push(
    `-- CreateTable ${model.name}\n${createTable(model)}\n` +
      (indexes.length ? `\n-- Indexes for ${model.name}\n${indexes.join('\n')}\n` : ''),
  )
}

const header = `-- Generated by scripts/generate-mysql-migration.mjs from prisma/schema.prisma.
--
-- Covers the models that existed only in the canonical schema: a MySQL
-- deployment built from the earlier migrations silently lacked these tables
-- while the SQLite runtime had them. Additive only — nothing is dropped or
-- narrowed.
--
-- DO NOT EDIT BY HAND. Edit prisma/schema.prisma, then run:
--   node scripts/generate-mysql-migration.mjs
--
-- Apply with:
--   npx prisma migrate deploy

`

const contents = header + sections.join('\n')

const dir = join(MIGRATIONS, NAME)
const target = join(dir, 'migration.sql')

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : ''
  if (current !== contents) {
    console.error(`FAIL: ${NAME}/migration.sql is out of date with prisma/schema.prisma.`)
    console.error('Run: node scripts/generate-mysql-migration.mjs')
    process.exit(1)
  }
  console.log(`PASS: ${NAME}/migration.sql matches the canonical schema.`)
  process.exit(0)
}

mkdirSync(dir, { recursive: true })
writeFileSync(target, contents)
console.log(`wrote ${NAME}/migration.sql — ${missing.length} tables`)
for (const model of missing) console.log('  +', model.table)
