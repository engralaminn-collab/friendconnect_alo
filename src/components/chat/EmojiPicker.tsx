export function EmojiPicker({ onPick, children }: { onPick: (emoji: string) => void; children?: React.ReactNode }) {
  const [open, setOpen] = useState(false)
  const [activeCategory, setActiveCategory] = useState<keyof typeof CATEGORIES>("Smileys & People")

  return (
    <Popover open={open} onOpenChange={setOpen}>
      <PopoverTrigger asChild>
        {children || (
          <Button variant="ghost" size="icon" className="rounded-full">
            <Smile className="w-5 h-5" />
          </Button>
        )}
      </PopoverTrigger>
      <PopoverContent className="w-80 p-0" align="start" side="top">
        {/* Category tabs */}
        <div className="flex gap-1 p-2 border-b overflow-x-auto">
          {Object.entries(CATEGORIES).map(([name, cat]) => (
            <button
              key={name}
              onClick={() => setActiveCategory(name as keyof typeof CATEGORIES)}
              className={`text-lg p-1.5 rounded-md shrink-0 ${
                activeCategory === name ? "bg-primary/20" : "hover:bg-muted"
              }`}
              title={name}
            >
              {cat.icon}
            </button>
          ))}
        </div>
        {/* Emoji grid */}
        <ScrollArea className="h-64">
          <div className="grid grid-cols-8 gap-0.5 p-2">
            {CATEGORIES[activeCategory].emojis.map((emoji, i) => (
              <button
                key={`${emoji}-${i}`}
                className="text-xl hover:bg-muted rounded p-1.5"
                onClick={() => {
                  onPick(emoji)
                  setOpen(false)
                }}
              >
                {emoji}
              </button>
            ))}
          </div>
        </ScrollArea>
        {/* Category label */}
        <div className="px-3 py-1.5 text-xs text-muted-foreground border-t">
          {activeCategory} ({CATEGORIES[activeCategory].emojis.length} emojis)
        </div>
      </PopoverContent>
    </Popover>
  )
}
